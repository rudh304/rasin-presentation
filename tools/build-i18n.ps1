# build-i18n.ps1 - copies assets/i18n/ar.json and en.json into assets/i18n/i18n.js,
# a script-loaded fallback used when index.html is opened via file:// (where fetch of JSON is blocked).
# Run after any edit to the JSON files:  powershell -ExecutionPolicy Bypass -File tools/build-i18n.ps1
$dir = Join-Path $PSScriptRoot '..\assets\i18n'
$ar  = Get-Content (Join-Path $dir 'ar.json') -Raw -Encoding UTF8
$en  = Get-Content (Join-Path $dir 'en.json') -Raw -Encoding UTF8
$out = "/* i18n.js - GENERATED by tools/build-i18n.ps1 from ar.json and en.json; do not edit by hand. */`nwindow.RASIN_I18N = {`n`"ar`": $ar,`n`"en`": $en`n};`n"
[System.IO.File]::WriteAllText((Join-Path $dir 'i18n.js'), $out, (New-Object System.Text.UTF8Encoding $false))
Write-Output "Wrote $(Join-Path $dir 'i18n.js')"
